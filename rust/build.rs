//! Builds the upstream C library the same way CMakeLists.txt does: run the
//! table generators into OUT_DIR, then compile the library sources with `cc`.

use std::env;
use std::path::{Path, PathBuf};
use std::process::Command;

/// The four generators CMake runs, in CMake's order.
const GENERATORS: [&str; 4] = [
    "gen_units.py",
    "gen_prefixes.py",
    "gen_currencies.py",
    "gen_profiles.py",
];

/// BVNR_SOURCES from CMakeLists.txt (lexer, validator, writer, io, dom,
/// stream, utils).
const SOURCES: [&str; 18] = [
    "src/lexer/bovnar_lexer.c",
    "src/lexer/bovnar_state_table.c",
    "src/validator/bovnar_validator.c",
    "src/writer/bovnar_writer.c",
    "src/writer/bovnar_write_utils.c",
    "src/writer/bovnar_canon_observer.c",
    "src/io/bovnar_io.c",
    "src/dom/bovnar_dom.c",
    "src/dom/bovnar_dom_builder.c",
    "src/stream/bovnar_stream.c",
    "src/utils/bovnar_utils.c",
    "src/utils/bovnar_si_units.c",
    "src/utils/bovnar_currency.c",
    "src/utils/bovnar_profiles.c",
    "src/utils/bvn_int.c",
    "src/utils/bvn_float.c",
    "src/utils/bvn_gregorian_date.c",
    "src/utils/bvn_datetime.c",
];

/// The profile switches, passed as 0/1 like CMake does: bvn_profile_impl.h
/// defaults each to 1 with #ifndef and tests it with #if.
const PROFILES: [(&str, u8); 7] = [
    ("BVNR_WITH_UCUM_PROFILE", 1),
    ("BVNR_WITH_UNECE_PROFILE", 1),
    ("BVNR_WITH_QUDT_PROFILE", 1),
    ("BVNR_WITH_QUDT_QK_PROFILE", 1),
    ("BVNR_WITH_UDUNITS_PROFILE", 1),
    ("BVNR_WITH_OM_PROFILE", 1),
    ("BVNR_WITH_CF_PROFILE", 1),
];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let repo = manifest
        .parent()
        .expect("rust/ lives inside the bovnar repository")
        .to_path_buf();
    let gen_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("generated");
    std::fs::create_dir_all(&gen_dir).expect("create OUT_DIR/generated");
    // The ABI unit test compiles tests/bvnr_abi_dump.c with the same `cc`
    // compiler as the library, which it can only find knowing the triples.
    for var in ["TARGET", "HOST"] {
        println!(
            "cargo:rustc-env=BVNR_BUILD_{var}={}",
            env::var(var).expect(var)
        );
    }

    println!("cargo:rerun-if-changed={}", repo.join("src").display());
    println!("cargo:rerun-if-changed={}", repo.join("include").display());
    println!(
        "cargo:rerun-if-changed={}",
        repo.join("bvnr_data.py").display()
    );
    for script in GENERATORS {
        println!("cargo:rerun-if-changed={}", repo.join(script).display());
    }
    println!("cargo:rerun-if-env-changed=WASI_SDK_PATH");

    generate_tables(&repo, &gen_dir);
    generate_base_units(&repo, &gen_dir);
    compile_library(&repo, &gen_dir);
}

/// Writes `base_units.rs`: the `BaseUnit` enum, one variant per base unit,
/// its upper-case name in CamelCase (`KILOGRAM_FORCE` is `KilogramForce`). Native units come from the C enum in
/// `include/bovnar_units.gen.h`; currencies from the generated catalogue, in
/// order from 900000. A currency code that clashes with a native unit name
/// gets a trailing `_` (`CUP_`, variant `Cup_`).
fn generate_base_units(repo: &Path, gen_dir: &Path) {
    let native = header_units(&repo.join("include/bovnar_units.gen.h"));
    // The opaque ids of the unit profiles (`ucum:[IU]` is `bu_ucum_iu`): real
    // `base_unit_t` values a parsed unit carries, which the enum must cover.
    let opaque = header_units(&repo.join("include/bovnar_profiles.gen.h"));
    let table = std::fs::read_to_string(gen_dir.join("bovnar_currency_table.gen.inc"))
        .expect("read the generated currency table");
    let codes: Vec<String> = table
        .lines()
        .filter_map(|l| l.trim().strip_prefix("{ \""))
        .filter_map(|l| l.split('"').next())
        .map(str::to_owned)
        .collect();

    // (upper-case name, variant, id)
    let mut members = vec![("NONE".to_owned(), "None".to_owned(), 0)];
    for (name, id) in native.iter().chain(&opaque) {
        members.push((name.clone(), camel(name), *id));
    }
    for (i, code) in codes.iter().enumerate() {
        let clash = native.iter().any(|(n, _)| n == code);
        let (name, variant) = if clash {
            (format!("{code}_"), format!("{}_", camel(code)))
        } else {
            (code.clone(), camel(code))
        };
        members.push((name, variant, 900_000 + i as i32));
    }
    let mut seen = std::collections::HashSet::new();
    for (name, variant, _) in &members {
        assert!(
            seen.insert(variant.clone()),
            "{name}: variant {variant} is not unique"
        );
    }

    let mut out = String::from(
        "// GENERATED by build.rs from the C unit enum and currency table.\n\
         /// Base-unit ids (`base_unit_t`): the native units and the\n\
         /// currencies, their upper-case names in CamelCase, plus the opaque\n\
         /// ids of the unit profiles (`UcumIu` for `ucum:[IU]`). The C\n\
         /// library is built from the same tables, so\n\
         /// every id it reports has a variant.\n\
         #[repr(i32)]\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Default)]\n\
         #[allow(non_camel_case_types)] // the `Cup_` style currency variants\n\
         pub enum BaseUnit {\n    #[default]\n",
    );
    for (_, variant, id) in &members {
        out.push_str(&format!("    {variant} = {id},\n"));
    }
    out.push_str(
        "}\n\nimpl BaseUnit {\n    /// Every member as (upper-case name, variant), in id order.\n    pub const MEMBERS: &[(&str, BaseUnit)] = &[\n",
    );
    for (name, variant, _) in &members {
        out.push_str(&format!("        (\"{name}\", BaseUnit::{variant}),\n"));
    }
    out.push_str(
        "    ];\n\n    /// The variant with C id `raw`, or `None` when there is none.\n    \
         pub fn from_raw(raw: i32) -> Option<Self> {\n        Some(match raw {\n",
    );
    for (_, variant, id) in &members {
        out.push_str(&format!("            {id} => BaseUnit::{variant},\n"));
    }
    out.push_str("            _ => return None,\n        })\n    }\n");
    let (first, last) = (
        native.first().expect("native units"),
        native.last().expect("native units"),
    );
    out.push_str(&format!(
        "}}\n\
         /// The first native base-unit id.\npub const UNIT_NATIVE_FIRST: i32 = {};\n\
         /// The last native base-unit id.\npub const UNIT_NATIVE_LAST: i32 = {};\n\
         /// The last currency id.\npub const CURRENCY_LAST: i32 = {};\n\
         /// The number of currencies.\npub const CURRENCY_COUNT: i32 = {};\n",
        first.1,
        last.1,
        900_000 + codes.len() as i32 - 1,
        codes.len()
    ));
    std::fs::write(gen_dir.join("base_units.rs"), out).expect("write base_units.rs");
}

/// The `bu_<name> = <id>,` lines of a generated header, as (NAME, id).
fn header_units(path: &Path) -> Vec<(String, i32)> {
    let header =
        std::fs::read_to_string(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let mut units = Vec::new();
    for line in header.lines() {
        let Some(rest) = line.trim().strip_prefix("bu_") else {
            continue;
        };
        let Some((name, value)) = rest.split_once('=') else {
            continue;
        };
        let value = value.trim().trim_end_matches(',');
        if let Ok(id) = value.parse::<i32>() {
            units.push((name.trim().to_ascii_uppercase(), id));
        }
    }
    units
}

/// `KILOGRAM_FORCE` -> `KilogramForce`.
fn camel(name: &str) -> String {
    name.split('_')
        .map(|part| {
            let mut chars = part.chars();
            chars.next().map_or_else(String::new, |c| {
                c.to_ascii_uppercase().to_string() + &chars.as_str().to_ascii_lowercase()
            })
        })
        .collect()
}

fn generate_tables(repo: &Path, gen_dir: &Path) {
    // $PYTHON first, then python3, then python (Windows installs only the latter).
    println!("cargo:rerun-if-env-changed=PYTHON");
    let candidates = env::var("PYTHON")
        .into_iter()
        .chain(["python3".to_owned(), "python".to_owned()]);
    let python = candidates
        .into_iter()
        .find(|p| matches!(Command::new(p).arg("--version").output(), Ok(out) if out.status.success()))
        .unwrap_or_else(|| {
            panic!(
                "Python 3 was not found. Building bovnar runs the upstream table \
                 generators (gen_units.py and friends); put python3 on PATH or set PYTHON."
            )
        });
    for script in GENERATORS {
        let status = Command::new(&python)
            .arg(repo.join(script))
            .current_dir(repo)
            .env("BVNR_GENERATED_DIR", gen_dir)
            // Keep the source tree free of __pycache__ from the build.
            .env("PYTHONDONTWRITEBYTECODE", "1")
            .status()
            .unwrap_or_else(|e| panic!("failed to run {python} {script}: {e}"));
        if !status.success() {
            panic!(
                "{python} {script} failed ({status}); the unit/prefix/currency tables were not generated"
            );
        }
    }
}

fn compile_library(repo: &Path, gen_dir: &Path) {
    let target = env::var("TARGET").expect("TARGET");
    let mut build = cc::Build::new();

    if target == "wasm32-wasip2" {
        let Some(sdk) = env::var_os("WASI_SDK_PATH").map(PathBuf::from) else {
            panic!(
                "building for wasm32-wasip2 needs a wasi-sdk: set WASI_SDK_PATH to \
                 its root (the directory containing bin/clang and share/wasi-sysroot)"
            );
        };
        build
            .compiler(sdk.join("bin/clang"))
            .archiver(sdk.join("bin/llvm-ar"))
            .flag(format!(
                "--sysroot={}",
                sdk.join("share/wasi-sysroot").display()
            ));
    }

    build
        .include(repo.join("include"))
        .include(gen_dir)
        .include(repo.join("src"));
    for sub in [
        "dom",
        "io",
        "lexer",
        "stream",
        "utils",
        "validator",
        "writer",
    ] {
        build.include(repo.join("src").join(sub));
    }
    for source in SOURCES {
        build.file(repo.join(source));
    }
    for (name, on) in PROFILES {
        build.define(name, on.to_string().as_str());
    }

    // The warning set of upstream's CMakeLists.txt (BVNR_C_FLAGS) instead of
    // cc's default -Wall -Wextra: upstream deliberately turns off
    // -Wmissing-field-initializers, which the generated profile tables trip
    // dozens of times.
    build.warnings(false);
    if build.get_compiler().is_like_msvc() {
        build.flag("/W3");
    } else {
        for flag in [
            "-Wall",
            "-Wextra",
            "-Wpedantic",
            "-Wshadow",
            "-Wcast-qual",
            "-Wconversion",
            "-Wno-missing-field-initializers",
            "-pedantic",
        ] {
            build.flag(flag);
        }
        if target.contains("windows-gnu") {
            build.flag("-Wno-float-conversion");
        }
    }

    if build.get_compiler().is_like_msvc() {
        build
            .flag("/std:c11")
            .flag("/utf-8")
            .define("_CRT_SECURE_NO_WARNINGS", None)
            .define("_CRT_NONSTDC_NO_WARNINGS", None);
    } else {
        // -fno-strict-aliasing: the source/sink structs are opaque storage the
        // library reinterprets through an internal impl struct (see CMake).
        build
            .flag("-std=c99")
            .flag("-fno-strict-aliasing")
            .flag("-fvisibility=hidden");
        if target.contains("windows-gnu") {
            build
                .define("__USE_MINGW_ANSI_STDIO", "1")
                .flag("-fno-builtin-printf")
                .flag("-fno-builtin-fprintf")
                .flag("-fno-builtin-snprintf");
        }
    }

    // CMake's Release configurations add -DNDEBUG; Debug keeps the asserts.
    if env::var("PROFILE").as_deref() == Ok("release") {
        build.define("NDEBUG", None);
    }

    build.compile("bvnr");
}
